// =================================================================================================
// pathResolver.rs — глобальный резолвер путей (проброс `chillffi/src/pathResolver.rs`).
//
// Уровней два: локальный — `scope.addSearchPath(dir)` (`scope.rs`),
// глобальный — `chillffi.addGlobalSearchPath(dir)` (этот файл). Сам резолв
// выполняет ядро в `Scope::load`: локальный путь скоупа → глобальный →
// путь как дан.
// =================================================================================================

/// Проброс `chillffi::pathResolver::addGlobalSearchPath` — добавить каталог в
/// глобальный путь поиска библиотек (общий на процесс список каталогов).
///
/// Относится ко всем скоупам, включая уже созданные и будущие: резолв
/// выполняет само ядро в `scope.load("имя")`, когда локального пути скоупа
/// нет или он не нашёл файл — локальный путь скоупа → глобальный → путь
/// как дан. Имя с разделителем пути (`/`, `\`) резолвер
/// пропускает — это не поиск, а прямой путь в dlopen.
///
/// ```python
/// chillffi.addGlobalSearchPath("/usr/local/lib")
/// with chillffi.Scope() as scope:
///     lib = scope.load("libfoo.so.1")   # нашлась глобальным резолвером
/// ```
///
/// Локальный аналог — `scope.addSearchPath(dir)` (виден только внутри блока).
#[pyfunction]
pub fn addGlobalSearchPath(path: String) -> ()
{
  chillffi::pathResolver::addGlobalSearchPath(path)
}

